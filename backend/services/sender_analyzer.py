import re


def analyze_sender(sender):
    """
    Analyze an email sender for suspicious patterns.

    Returns:
        score: risk points generated by sender analysis
        findings: explanations for the score
    """

    score = 0
    findings = []

    sender = (sender or "").strip().lower()

    # Check whether sender exists
    if not sender:
        return {
            "score": 20,
            "findings": ["Sender address is missing."]
        }

    # Basic email format check
    if "@" not in sender:
        return {
            "score": 20,
            "findings": [
                "Sender does not appear to be a valid email address."
            ]
        }

    username, domain = sender.split("@", 1)

    # Suspicious terms
    suspicious_terms = [
        "security-alert",
        "account-check",
        "payment-warning",
        "verify",
        "login",
        "support-alert"
    ]

    for term in suspicious_terms:
        if term in domain or term in username:
            score += 10
            findings.append(
                f"Sender contains suspicious term: {term}"
            )

    # Synthetic suspicious-domain pattern
    if domain.endswith(".invalid.test"):
        score += 15
        findings.append(
            "Sender uses a synthetic suspicious-domain pattern."
        )

    # Too many subdomains
    domain_parts = domain.split(".")

    if len(domain_parts) > 3:
        score += 10
        findings.append(
            "Sender domain contains an unusually large number "
            "of subdomains."
        )

    # Numbers in domain
    if re.search(r"\d", domain):
        score += 5
        findings.append(
            "Sender domain contains numeric characters."
        )

    return {
        "score": min(score, 100),
        "findings": findings
    }